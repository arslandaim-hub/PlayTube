package com.arslandaim.playtube.utils

import androidx.media3.common.MimeTypes
import java.util.Locale

object CaptionTrackResolver {

    /**
     * Normalizes raw subtitle URLs to WebVTT parseable by Media3.
     * YouTube api/timedtext URLs are forced to WebVTT (&fmt=vtt) for universal 200 OK responses.
     */
    fun normalizeSubtitleUrl(rawUrl: String, format: String? = null): Pair<String, String> {
        if (rawUrl.isBlank()) return Pair("", MimeTypes.TEXT_VTT)

        if (rawUrl.contains("/api/timedtext")) {
            // Strip any existing &fmt=srv1, &fmt=srv2, &fmt=srv3, &fmt=json3, &fmt=vtt, &fmt=ttml
            var cleanUrl = rawUrl.replace(Regex("[?&]fmt=(srv[123]|json3|vtt|ttml)"), "")
            // Ensure valid query string syntax
            if (!cleanUrl.contains("?")) {
                val firstAmp = cleanUrl.indexOf('&')
                if (firstAmp != -1) {
                    cleanUrl = cleanUrl.substring(0, firstAmp) + "?" + cleanUrl.substring(firstAmp + 1)
                }
            }

            val delimiter = if (cleanUrl.contains("?")) "&" else "?"
            val finalUrl = "$cleanUrl${delimiter}fmt=vtt"
            return Pair(finalUrl, MimeTypes.TEXT_VTT)
        }

        // Local file or direct URLs
        val lowerUrl = rawUrl.lowercase()
        val lowerFmt = format?.lowercase() ?: ""
        val mimeType = when {
            lowerUrl.endsWith(".srt") || lowerFmt == "srt" -> MimeTypes.APPLICATION_SUBRIP
            lowerUrl.endsWith(".vtt") || lowerFmt == "vtt" -> MimeTypes.TEXT_VTT
            lowerUrl.endsWith(".ttml") || lowerUrl.endsWith(".xml") || lowerFmt == "ttml" -> MimeTypes.APPLICATION_TTML
            else -> MimeTypes.TEXT_VTT
        }
        return Pair(rawUrl, mimeType)
    }

    /**
     * Builds a human-readable display label for a subtitle track.
     */
    fun buildDisplayLabel(languageTag: String, isAutoGenerated: Boolean, customName: String? = null): String {
        if (!customName.isNullOrBlank()) return customName
        val langName = try {
            val locale = Locale.forLanguageTag(languageTag)
            locale.displayLanguage.ifBlank { languageTag }
        } catch (e: Exception) {
            languageTag
        }
        return if (isAutoGenerated) "$langName (Auto-generated)" else langName
    }
}
