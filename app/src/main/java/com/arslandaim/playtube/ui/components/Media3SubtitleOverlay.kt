@Composable
fun Media3SubtitleOverlay(
    player: Player?,
    enabled: Boolean,
    modifier: Modifier = Modifier,
    externalCues: List<Cue> = emptyList(),
    isAutoGenerated: Boolean = false,
    fontSizeSp: Float = 16f,
    backgroundOpacity: Float = 0.65f,
    bottomPaddingDp: Float = 48f
) {
    var listenerCues by remember { mutableStateOf(emptyList<Cue>()) }

    DisposableEffect(player) {
        if (player == null) {
            onDispose { }
        } else {
            val listener = object : Player.Listener {
                override fun onCues(cueGroup: CueGroup) {
                    listenerCues = cueGroup.cues
                    if (listenerCues.isNotEmpty()) {
                        PTLog.d("Media3SubtitleOverlay", "Received ${listenerCues.size} cues. First: ${listenerCues.first().text}")
                    }
                }
            }
            player.addListener(listener)
            listenerCues = player.currentCues.cues
            onDispose {
                player.removeListener(listener)
            }
        }
    }

    val activeCues = if (listenerCues.isNotEmpty()) listenerCues else externalCues

    val displayText = remember(enabled, isAutoGenerated, activeCues) {
        if (!enabled) null else activeCues.toSubtitleDisplayText()
    }

    AnimatedVisibility(
        visible = displayText != null,
        enter = fadeIn() + slideInVertically { it / 2 },
        exit = fadeOut() + slideOutVertically { it / 2 },
        modifier = modifier.fillMaxSize()
    ) {
        if (displayText != null) {
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(horizontal = 16.dp),
                contentAlignment = Alignment.BottomCenter
            ) {
                Surface(
                    color = Color.Black.copy(alpha = backgroundOpacity),
                    shape = RoundedCornerShape(4.dp),
                    modifier = Modifier.offset(y = (-bottomPaddingDp).dp)
                ) {
                    Text(
                        text = displayText,
                        color = Color.White,
                        fontSize = fontSizeSp.sp,
                        fontWeight = FontWeight.Medium,
                        textAlign = TextAlign.Center,
                        maxLines = 1,
                        softWrap = false,
                        overflow = TextOverflow.Ellipsis,
                        lineHeight = (fontSizeSp * 1.25f).sp,
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp)
                    )
                }
            }
        }
    }
}

private fun List<Cue>.toSubtitleDisplayText(): String? {
    if (isEmpty()) return null

    val cleanedTexts = mapNotNull { cue ->
        val raw = cue.text?.toString() ?: ""
        val clean = SubtitleSanitizer.cleanCueText(raw)
        clean.ifBlank { null }
    }.distinct()

    if (cleanedTexts.isEmpty()) return null

    // Take the latest active cue and normalize onto a single horizontal line
    val singleLine = cleanedTexts.last()
        .replace("\n", " ")
        .replace(Regex("\\s+"), " ")
        .trim()

    return singleLine.ifBlank { null }
}
