@Composable
fun Media3SubtitleOverlay(
    player: Player?,
    enabled: Boolean,
    modifier: Modifier = Modifier,
    isAutoGenerated: Boolean = false,
    fontSizeSp: Float = 16f,
    backgroundOpacity: Float = 0.65f,
    bottomPaddingDp: Float = 48f
) {
    var cues by remember { mutableStateOf(emptyList<Cue>()) }

    DisposableEffect(player) {
        if (player == null) {
            onDispose { }
        } else {
            val listener = object : Player.Listener {
                override fun onCues(cueGroup: CueGroup) {
                    cues = cueGroup.cues
                    if (cues.isNotEmpty()) {
                        PTLog.d("Media3SubtitleOverlay", "Received ${cues.size} cues. First: ${cues.first().text}")
                    }
                }
            }
            player.addListener(listener)
            cues = player.currentCues.cues
            onDispose {
                player.removeListener(listener)
            }
        }
    }

    val displayText = remember(enabled, isAutoGenerated, cues) {
        if (!enabled) null else cues.toSubtitleDisplayText(isAutoGenerated)
    }

    AnimatedVisibility(
        visible = displayText != null,
        enter = fadeIn() + slideInVertically { it / 2 },
        exit = fadeOut() + slideOutVertically { it / 2 },
        modifier = modifier.fillMaxSize()
    ) {
        if (displayText != null) {
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(horizontal = 16.dp),
                contentAlignment = Alignment.BottomCenter
            ) {
                Surface(
                    color = Color.Black.copy(alpha = backgroundOpacity),
                    shape = RoundedCornerShape(4.dp),
                    modifier = Modifier.offset(y = (-bottomPaddingDp).dp)
                ) {
                    Text(
                        text = displayText,
                        color = Color.White,
                        fontSize = fontSizeSp.sp,
                        fontWeight = FontWeight.Medium,
                        textAlign = TextAlign.Center,
                        lineHeight = (fontSizeSp * 1.25f).sp,
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp)
                    )
                }
            }
        }
    }
}

private fun List<Cue>.toSubtitleDisplayText(isAutoGenerated: Boolean): String? {
    if (isEmpty()) return null

    val cleanedTexts = mapNotNull { cue ->
        val raw = cue.text?.toString() ?: ""
        val clean = SubtitleSanitizer.cleanCueText(raw)
        clean.ifBlank { null }
    }

    if (cleanedTexts.isEmpty()) return null

    val combined = cleanedTexts.distinct().joinToString(" ").replace(Regex("\\s+"), " ").trim()
    if (combined.isBlank()) return null

    if (combined.length > 45) {
        val words = combined.split(" ")
        if (words.size > 3) {
            val targetLen = combined.length / 2
            var currentLen = 0
            var splitIndex = -1
            for (i in words.indices) {
                currentLen += words[i].length + 1
                if (currentLen >= targetLen) {
                    splitIndex = i
                    break
                }
            }
            if (splitIndex in 1 until words.size - 1) {
                val line1 = words.subList(0, splitIndex + 1).joinToString(" ")
                val line2 = words.subList(splitIndex + 1, words.size).joinToString(" ")
                return "$line1\n$line2"
            }
        }
    }

    return combined
}
